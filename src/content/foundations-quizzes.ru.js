import {
  FOUNDATIONS_QUIZ_I18N,
  FOUNDATIONS_QUIZ_LANGS,
} from './foundations-quizzes.i18n.js';

export const FOUNDATIONS_QUIZ_TOPICS_RU = [
  'preinternet', 'web1', 'web2', 'social', 'web30', 'web3', 'economy', 'netocracy',
];

const LAST_SCENE = {
  preinternet: 'preinternet:8',
  web1: 'web1:5',
  web2: 'web2:6',
  social: 'social:6',
  web30: 'web30:5',
  web3: 'web3:7',
  economy: 'economy:6',
  netocracy: 'netocracy:6',
};

function question(topic, n, nodeId, prompt, correct, wrong1, wrong2, why) {
  const id = `${topic}:q${String(n).padStart(2, '0')}`;
  const translated = FOUNDATIONS_QUIZ_I18N[id] || {};
  const copy = { ru: [prompt, correct, wrong1, wrong2, why], ...translated };
  const localized = (index) => Object.fromEntries(
    FOUNDATIONS_QUIZ_LANGS.map((lang) => [lang, copy[lang]?.[index]]),
  );
  return {
    id,
    topic_key: topic,
    scene_ck: LAST_SCENE[topic],
    node_id: nodeId,
    prompt: localized(0),
    options: [
      { id: 'a', text: localized(1), is_correct: true },
      { id: 'b', text: localized(2), is_correct: false },
      { id: 'c', text: localized(3), is_correct: false },
    ],
    why: localized(4),
    status: 'published',
    sort: n,
  };
}

